import type { GenealogyEdge } from "./types";

const explicit = (
  from: string,
  to: string,
  refs: string[],
  extra?: Partial<GenealogyEdge>,
): GenealogyEdge => ({
  from,
  to,
  relationship: "parent-of",
  viaParent: "father",
  relationKind: "biological",
  scriptureReferences: refs,
  confidenceLevel: "explicit",
  ...extra,
});

const motherOf = (
  from: string,
  to: string,
  refs: string[],
  extra?: Partial<GenealogyEdge>,
): GenealogyEdge => ({
  from,
  to,
  relationship: "parent-of",
  viaParent: "mother",
  relationKind: "biological",
  scriptureReferences: refs,
  confidenceLevel: "explicit",
  ...extra,
});

const spouse = (
  a: string,
  b: string,
  refs: string[],
  extra?: Partial<GenealogyEdge>,
): GenealogyEdge[] => [
  {
    from: a,
    to: b,
    relationship: "spouse-of",
    relationKind: "biological",
    scriptureReferences: refs,
    confidenceLevel: "explicit",
    ...extra,
  },
  {
    from: b,
    to: a,
    relationship: "spouse-of",
    relationKind: "biological",
    scriptureReferences: refs,
    confidenceLevel: "explicit",
    ...extra,
  },
];

